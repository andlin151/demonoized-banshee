#!/usr/bin/env python3
# Generates SDK-style .csproj files from the autotools Makefile.am of each project.
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

HYENA = '$(HyenaDir)Hyena/Hyena.csproj'
HYENA_SQLITE = '$(HyenaDir)Hyena.Data.Sqlite/Hyena.Data.Sqlite.csproj'
HYENA_GUI = '$(HyenaDir)Hyena.Gui/Hyena.Gui.csproj'
DBUS = '$(DBusSharpDir)src/dbus-sharp.csproj'
DBUS_GLIB = '$(DBusSharpGlibDir)src/dbus-sharp-glib.csproj'

def p(rel):
    return '$(MSBuildThisFileDirectory)../../' + rel  # relative to src/<Group>/<Project>/

MONO_MEDIA = p('Libraries/Mono.Media/Mono.Media.csproj')
MUSICBRAINZ = p('Libraries/MusicBrainz/MusicBrainz.csproj')
LASTFM = p('Libraries/Lastfm/Lastfm.csproj')
CORE = p('Core/Banshee.Core/Banshee.Core.csproj')
SERVICES = p('Core/Banshee.Services/Banshee.Services.csproj')
WIDGETS = p('Core/Banshee.Widgets/Banshee.Widgets.csproj')
THICKCLIENT = p('Core/Banshee.ThickClient/Banshee.ThickClient.csproj')

PKG = {
    'gtk': ('GtkSharp', '$(GtkSharpVersion)'),
    'glib': ('GLibSharp', '$(GtkSharpVersion)'),
    'gio': ('GioSharp', '$(GtkSharpVersion)'),
    'posix': ('Mono.Posix', '$(MonoPosixVersion)'),
    'addins': ('Mono.Addins', '1.4.1'),
    # Mono.Addins needs Cecil to scan assemblies when running on .NET Core and later
    'addins-cecil': ('Mono.Addins.CecilReflector', '1.4.1'),
    'taglib': ('TagLibSharp', '2.3.0'),
    'zip': ('SharpZipLib', '1.4.2'),
}

PROJECTS = [
    # dir, output type, unsafe, defines, project refs, packages, extra sources excluded
    ('src/Libraries/Mono.Media', 'Library', False, [], [], []),
    ('src/Libraries/MusicBrainz', 'Library', False, [], [], []),
    ('src/Libraries/Lastfm', 'Library', False, [], [MONO_MEDIA, HYENA, HYENA_SQLITE], ['posix', 'glib', 'zip']),
    ('src/Core/Banshee.Core', 'Library', False, [], [LASTFM, HYENA, HYENA_SQLITE, DBUS], ['posix', 'glib', 'addins', 'taglib']),
    ('src/Core/Banshee.Services', 'Library', False, [], [MONO_MEDIA, CORE, MUSICBRAINZ, LASTFM, HYENA, HYENA_SQLITE, DBUS, DBUS_GLIB], ['posix', 'glib', 'addins', 'addins-cecil', 'taglib', 'zip']),
    ('src/Core/Banshee.Widgets', 'Library', True, [], [HYENA, HYENA_SQLITE, HYENA_GUI], ['posix', 'gtk']),
    ('src/Core/Banshee.ThickClient', 'Library', True, [], [SERVICES, CORE, WIDGETS, HYENA, HYENA_SQLITE, HYENA_GUI, DBUS, DBUS_GLIB], ['posix', 'gtk', 'addins', 'taglib', 'zip']),
    ('src/Backends/Banshee.Unix', 'Library', False, [], [CORE, HYENA], ['posix', 'glib', 'taglib', 'addins']),
    ('src/Backends/Banshee.GStreamer', 'Library', False, [], [SERVICES, CORE, HYENA, HYENA_SQLITE], ['posix', 'gtk', 'addins']),
    ('src/Backends/Banshee.Gio', 'Library', False, [], [CORE, SERVICES, HYENA], ['posix', 'gtk', 'taglib', 'addins']),
    ('src/Clients/Nereid', 'WinExe', False, [], [THICKCLIENT, SERVICES, CORE, WIDGETS, HYENA, HYENA_SQLITE, HYENA_GUI], ['posix', 'gtk', 'addins']),
    ('src/Clients/Booter', 'Exe', False, [], [SERVICES, CORE, HYENA, HYENA_SQLITE, DBUS], ['posix', 'glib', 'addins']),
]

def makefile_list(text, var):
    m = re.search(r'^%s\s*=(.*?)(?<!\\)\n' % var, text, re.M | re.S)
    if not m:
        return []
    return [t for t in re.split(r'[\s\\]+', m.group(1)) if t]

def var(text, name):
    m = re.search(r'^%s\s*=\s*(\S+)' % name, text, re.M)
    return m.group(1) if m else None

for d, out, unsafe, defines, refs, pkgs in PROJECTS:
    mk = open(os.path.join(ROOT, d, 'Makefile.am')).read()
    asm = var(mk, 'ASSEMBLY')
    sources = makefile_list(mk, 'SOURCES')
    resources = makefile_list(mk, 'RESOURCES')
    old = [f for f in os.listdir(os.path.join(ROOT, d)) if f.endswith('.csproj')]
    name = old[0] if old else asm + '.csproj'
    lines = ['<Project Sdk="Microsoft.NET.Sdk">',
             '  <!-- Generated by build/dotnet/gen-csproj.py from Makefile.am -->',
             '  <PropertyGroup>',
             '    <AssemblyName>%s</AssemblyName>' % asm,
             '    <RootNamespace>%s</RootNamespace>' % asm,
             '    <OutputType>%s</OutputType>' % out]
    if unsafe:
        lines.append('    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>')
    if defines:
        lines.append('    <DefineConstants>$(DefineConstants);%s</DefineConstants>' % ';'.join(defines))
    lines.append('  </PropertyGroup>')
    lines.append('  <ItemGroup>')
    lines += ['    <Compile Include="%s" />' % s for s in sources]
    lines.append('  </ItemGroup>')
    if resources:
        lines.append('  <ItemGroup>')
        lines += ['    <EmbeddedResource Include="%s" />' % r for r in resources]
        lines.append('  </ItemGroup>')
    if refs:
        lines.append('  <ItemGroup>')
        lines += ['    <ProjectReference Include="%s" />' % r for r in refs]
        lines.append('  </ItemGroup>')
    if pkgs:
        lines.append('  <ItemGroup>')
        lines += ['    <PackageReference Include="%s" Version="%s" />' % PKG[k] for k in pkgs]
        lines.append('  </ItemGroup>')
    lines.append('</Project>')
    path = os.path.join(ROOT, d, name)
    open(path, 'w').write('\n'.join(lines) + '\n')
    print('%-45s %3d sources %2d resources' % (os.path.relpath(path, ROOT), len(sources), len(resources)))
